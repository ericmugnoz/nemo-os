// verdad hacian falta: un boton de 'atras' con una flecha salia vacio.
const glifo_extra_t font5x7_extras[] = {
    { 0x2013, {0x00,0x00,0x00,0x1F,0x00,0x00,0x00} },   // –
    { 0x2014, {0x00,0x00,0x00,0x1F,0x00,0x00,0x00} },   // —
    { 0x2018, {0x04,0x04,0x08,0x00,0x00,0x00,0x00} },   // ‘
    { 0x2019, {0x04,0x04,0x02,0x00,0x00,0x00,0x00} },   // ’
    { 0x201C, {0x0A,0x0A,0x12,0x00,0x00,0x00,0x00} },   // “
    { 0x201D, {0x0A,0x0A,0x09,0x00,0x00,0x00,0x00} },   // ”
    { 0x2022, {0x00,0x00,0x0E,0x0E,0x0E,0x00,0x00} },   // •
    { 0x2026, {0x00,0x00,0x00,0x00,0x00,0x00,0x15} },   // …
    { 0x20AC, {0x07,0x08,0x1F,0x08,0x1F,0x08,0x07} },   // €
    { 0x2190, {0x00,0x04,0x08,0x1F,0x08,0x04,0x00} },   // ←
    { 0x2191, {0x04,0x0E,0x15,0x04,0x04,0x04,0x00} },   // ↑
    { 0x2192, {0x00,0x04,0x02,0x1F,0x02,0x04,0x00} },   // →
    { 0x2193, {0x00,0x04,0x04,0x04,0x15,0x0E,0x04} },   // ↓
};
const uint32_t font5x7_num_extras = sizeof(font5x7_extras) / sizeof(font5x7_extras[0]);

// El glifo de un codigo, venga de donde venga. NULL si la fuente no lo
// tiene: quien dibuja decide entonces que hacer (un hueco).
const uint8_t *font5x7_glifo(uint32_t cod) {
    if (cod < 256) return font5x7[cod];
    for (uint32_t i = 0; i < font5x7_num_extras; i++)
        if (font5x7_extras[i].cod == cod) return font5x7_extras[i].filas;
    return 0;
}
